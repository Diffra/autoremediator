/**
 * What a change request says and how many there are: the title and body for a group of reports,
 * the option checks that pick provider and grouping, and the grouping itself.
 */
import type { RemediationReport } from "../remediate/types.js";
import { CHANGE_REQUEST_PROVIDER_VALUES } from "./types.js";
import type {
  ChangeRequestGrouping,
  ChangeRequestOptions,
  ChangeRequestProvider,
} from "./types.js";

export interface ChangeRequestPlan {
  cveIds: string[];
  packageNames: string[];
  title: string;
  body: string;
}

export function buildPlan(reports: RemediationReport[]): ChangeRequestPlan {
  const cveIds = [...new Set(reports.map((report) => report.cveId))];
  const packageNames = [
    ...new Set(reports.flatMap((report) => report.results.map((result) => result.packageName))),
  ];

  // A freshness step upgrades a dependency to stay current: it is not a security remediation.
  if (reports.length > 0 && reports.every((report) => report.cveId.startsWith("FRESHNESS-"))) {
    const moves = reports.flatMap((report) =>
      report.results.map(
        (result) => `${result.packageName} ${result.fromVersion} -> ${result.toVersion ?? "?"}`,
      ),
    );
    return {
      cveIds,
      packageNames,
      title: `dependency freshness: ${moves.join(", ")}`,
      body: [
        "Automated dependency freshness step generated by autoremediator.",
        "",
        ...moves.map((move) => `- ${move}`),
      ].join("\n"),
    };
  }

  const titleSuffix = cveIds.length === 1 ? cveIds[0]! : `${cveIds.length} CVEs`;
  const title = `security remediation: ${titleSuffix}`;
  const body = [
    "Automated remediation generated by autoremediator.",
    "",
    `CVEs: ${cveIds.join(", ")}`,
    `Packages: ${packageNames.join(", ")}`,
  ].join("\n");

  return {
    cveIds,
    packageNames,
    title,
    body,
  };
}

export function resolveProvider(options: ChangeRequestOptions): ChangeRequestProvider {
  const provider = options.provider ?? "github";
  if (!CHANGE_REQUEST_PROVIDER_VALUES.includes(provider)) {
    throw new Error(
      `Unsupported changeRequest.provider: "${provider}". Supported values: ${CHANGE_REQUEST_PROVIDER_VALUES.join(", ")}`,
    );
  }
  return provider;
}

export function resolveGrouping(options: ChangeRequestOptions): ChangeRequestGrouping {
  const allowed: ChangeRequestGrouping[] = ["all", "per-cve", "per-package", "by-severity"];
  if (options.grouping && !allowed.includes(options.grouping)) {
    throw new Error(
      `Unsupported changeRequest.grouping: "${options.grouping}". Supported values: ${allowed.join(", ")}`,
    );
  }
  return options.grouping ?? "all";
}

export function groupReports(
  reports: RemediationReport[],
  grouping: ChangeRequestGrouping,
): RemediationReport[][] {
  if (reports.length === 0) return [];
  if (grouping === "all") {
    return [reports];
  }
  if (grouping === "per-cve") {
    return groupByKey(reports, (report) => [report.cveId.toUpperCase()]);
  }
  if (grouping === "per-package") {
    return groupByKey(reports, packageKeys);
  }
  if (grouping === "by-severity") {
    return groupByKey(reports, (report) => [report.cveDetails?.severity ?? "UNKNOWN"]);
  }
  return [reports];
}

/** The packages a report touched, or `misc` when it touched none. */
function packageKeys(report: RemediationReport): string[] {
  const pkgs = new Set(report.results.map((r) => r.packageName));
  return pkgs.size === 0 ? ["misc"] : [...pkgs];
}

function groupByKey(
  reports: RemediationReport[],
  keysOf: (report: RemediationReport) => string[],
): RemediationReport[][] {
  const map = new Map<string, RemediationReport[]>();
  for (const report of reports) {
    for (const key of keysOf(report)) {
      const list = map.get(key) ?? [];
      list.push(report);
      map.set(key, list);
    }
  }
  return [...map.values()];
}
